// Run only against the disposable loopback preview, never a hosted database.
import assert from 'node:assert/strict';
const base='http://127.0.0.1:5173';
const auth=await fetch(base+'/signin-with-chatgpt?return_to=/',{redirect:'manual'});
const cookie=auth.headers.getSetCookie().map(c=>c.split(';')[0]).join('; ');
assert.ok(cookie,'Local preview auth cookie required');
const get=async()=>{const r=await fetch(base+'/api/guild',{headers:{cookie}});assert.equal(r.status,200);return r.json();};
const post=async(body,status=200,authenticated=true,origin=base)=>{const r=await fetch(base+'/api/guild',{method:'POST',headers:{'Content-Type':'application/json',origin,...(authenticated?{cookie}:{})},body:JSON.stringify(body)});const raw=await r.text();let d;try{d=JSON.parse(raw);}catch{d={error:raw};}assert.equal(r.status,status,JSON.stringify(d));return d;};
let d=await get();
if(d.me&&!['Nara Uji','QA Petualang','QA Nama Baru'].includes(d.me.name))throw Error('Refusing to modify a non-test local character.');
await post({action:'update',name:'No',role:'Penjaga',color:'#e99552'},401,false);
await post({action:'delete'},403,true,'https://example.invalid');
await post(null,400);
if(!d.me)d=await post({action:'join',gender:'laki-laki',name:'QA Petualang',role:'Penjaga',color:'#e99552'});
const bed=d.me.bed,joinedAt=d.me.joinedAt;
d=await post({action:'update',name:'QA Nama Baru',role:'Peramu',color:'#8baf9c',id:'someone-else'});
assert.equal(d.me.name,'QA Nama Baru');assert.equal(d.me.role,'Peramu');assert.equal(d.me.bed,bed);assert.equal(d.me.joinedAt,joinedAt);
await post({action:'update',name:'X',role:'Admin',color:'#fff'},400);
assert.equal((await get()).me.name,'QA Nama Baru');
await post({action:'reset'},400);
d=await post({action:'reset',confirmation:'MULAI ULANG'});
assert.equal(d.me.xp,0);assert.equal(d.me.wood,0);assert.equal(d.me.herbs,0);
d=await post({action:'wood'});assert.equal(d.me.xp,12);assert.equal(d.me.wood,1);
await post({action:'wood'},429);
const oldRole=d.me.role,oldColor=d.me.color;
await post({action:'reroll'},400);
d=await post({action:'reroll',confirmation:'ACAK ULANG'});
assert.notEqual(d.me.role,oldRole);assert.notEqual(d.me.color,oldColor);assert.equal(d.me.xp,12);assert.equal(d.me.wood,1);assert.equal(d.me.bed,bed);
d=await post({action:'reset',confirmation:'MULAI ULANG'});
assert.equal(d.me.xp,0);assert.equal(d.me.wood,0);assert.equal(d.me.lastAction,0);assert.equal(d.me.bed,bed);assert.equal(d.me.name,'QA Nama Baru');
await post({action:'delete',confirmation:'HAPUS',characterName:'Wrong name'},400);
assert.ok((await get()).me);
d=await post({action:'delete',confirmation:'HAPUS',characterName:'QA Nama Baru'});
assert.equal(d.me,null);assert.ok(!d.members.some(m=>m.bed===bed));assert.equal((await get()).me,null);
await post({action:'update',name:'QA Nama Baru',role:'Peramu',color:'#8baf9c'},404);
d=await post({action:'join',gender:'laki-laki',name:'QA Petualang',role:'Penjelajah',color:'#e99552'});
assert.equal(d.me.xp,0);assert.equal(d.me.wood,0);assert.notEqual(d.me.bed,bed);
console.log('PASS: auth, origin, validation, rename, reroll, cooldown, reset, deletion, persistence and rejoin. Test character is local-only.');
