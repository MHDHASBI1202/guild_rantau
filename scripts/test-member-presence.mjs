import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import ts from 'typescript';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
await mkdir('outputs/presence-tests',{recursive:true});
const source=await readFile('app/member-presence.ts','utf8');
await writeFile('outputs/presence-tests/presence.mjs',ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText);
const p=await import('../outputs/presence-tests/presence.mjs'),db=new DatabaseSync(':memory:'),now=1_000_000;
db.exec('CREATE TABLE members(id TEXT PRIMARY KEY,xp INTEGER,last_action INTEGER,joined_at INTEGER); CREATE TABLE auth_sessions(user_id TEXT,expires_at INTEGER);');
for(let i=0;i<9;i++)db.prepare('INSERT INTO members VALUES(?,?,?,?)').run('user-'+i,42,now,now);
db.exec(await readFile('drizzle/0007_glamorous_meggan.sql','utf8'));
for(let i=0;i<10;i++)db.prepare('INSERT INTO auth_sessions VALUES(?,?)').run('user-'+i,now+30*86400000);
db.prepare('INSERT INTO auth_sessions VALUES(?,?)').run('user-0',now+30*86400000);
const counts=(time=now)=>{const row=db.prepare(p.MEMBER_COUNTS_SQL).get(time-p.ACTIVE_MEMBER_WINDOW_MS);assert.ok(row.activeCount<=row.total);return {...row};};
const heartbeat=(id,time=now)=>db.prepare(p.MEMBER_HEARTBEAT_SQL).run(time,id,time-p.MEMBER_HEARTBEAT_INTERVAL_MS);
assert.equal(db.prepare('SELECT COUNT(DISTINCT user_id) AS count FROM auth_sessions').get().count,10);
assert.deepEqual(counts(),{total:9,activeCount:0},'Old login sessions and recent actions are not online presence');
assert.equal(heartbeat('user-0').changes,1);assert.deepEqual(counts(),{total:9,activeCount:1});
assert.equal(heartbeat('user-0',now+1000).changes,0,'Extra tabs do not add players or write every second');
assert.equal(heartbeat('user-9').changes,0,'A signed-in account without a character does not count');
assert.equal(heartbeat('guest').changes,0);assert.deepEqual(counts(),{total:9,activeCount:1});
heartbeat('user-1');assert.deepEqual(counts(),{total:9,activeCount:2});
assert.equal(heartbeat('user-0',now+p.MEMBER_HEARTBEAT_INTERVAL_MS).changes,1);
assert.equal(db.prepare('SELECT xp FROM members WHERE id=?').get('user-0').xp,42,'Presence never gives XP');
assert.deepEqual(counts(now+p.ACTIVE_MEMBER_WINDOW_MS),{total:9,activeCount:1});
assert.deepEqual(counts(now+p.MEMBER_HEARTBEAT_INTERVAL_MS+p.ACTIVE_MEMBER_WINDOW_MS),{total:9,activeCount:0});
heartbeat('user-0',now+300000);db.prepare('DELETE FROM members WHERE id=?').run('user-0');
assert.deepEqual(counts(now+300000),{total:8,activeCount:0},'Deleted members cannot remain in the active count');
db.exec('DELETE FROM members');assert.deepEqual(counts(now+300000),{total:0,activeCount:0});
db.close();console.log('PASS: reproduce 10 sessions/9 characters; no false minimum, member-only presence, multi-tab deduplication, throttled writes, expiry, deletion, migration preservation and unchanged XP.');
